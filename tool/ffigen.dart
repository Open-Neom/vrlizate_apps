import 'dart:io';

import 'package:ffigen/ffigen.dart';

void main() {
  final packageRoot = Platform.script.resolve('../');
  final entryHeader = packageRoot.resolve('native/include/posix_stream_io.h');
  final bindingsOutput = packageRoot.resolve(
    'lib/src/third_party/posix_stream_io.g.dart',
  );
  const ffiLib = LibraryImport('ffi', 'dart:ffi');
  final cInt = ImportedType(ffiLib, 'Int', 'int', 'int', defaultValue: '0');

  FfiGenerator(
    headers: Headers(
      entryPoints: <Uri>[entryHeader],
      include: (Uri header) => header.path.endsWith('posix_stream_io.h'),
    ),
    functions: Functions(
      include: Declarations.includeSet(const <String>{
        'malloc',
        'free',
        'open',
        'close',
        'fcntl',
        'lseek',
        'lseek64',
        'pread',
        'pread64',
        'mmap',
        'mmap64',
        'munmap',
      }),
      isLeaf: Declarations.includeSet(const <String>{
        'malloc',
        'free',
        'close',
        'fcntl',
        'lseek',
        'lseek64',
        'mmap',
        'mmap64',
        'munmap',
      }),
      varArgs: <String, List<VarArgFunction>>{
        'open': <VarArgFunction>[VarArgFunction('', const <ImportedType>[])],
        'fcntl': <VarArgFunction>[VarArgFunction('Int', <ImportedType>[cInt])],
      },
    ),
    output: Output(
      dartFile: bindingsOutput,
      commentType: const CommentType.none(),
      format: true,
      style: const DynamicLibraryBindings(
        wrapperName: 'PosixStreamIoBindings',
        wrapperDocComment:
            'Generated POSIX C-ABI bindings for zero-unpack VRLZ streaming.',
      ),
      preamble: '''
